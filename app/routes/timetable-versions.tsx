import {
  useLoaderData,
  useSubmit,
  Link,
  type ActionFunctionArgs,
  type LoaderFunctionArgs,
} from "react-router";
import {
  History,
  FileCheck,
  Calendar,
  Sparkles,
  Trash2,
  Eye,
  CheckCircle2,
  Clock,
  Layers,
} from "lucide-react";
import { requireRole } from "~/services/auth.server";
import { getAllTimetableVersions, publishTimetableVersion, deleteTimetableVersion } from "~/services/timetable.server";
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from "~/components/ui/card";
import { Button } from "~/components/ui/button";
import { Badge } from "~/components/ui/badge";

export async function loader({ request }: LoaderFunctionArgs) {
  const user = await requireRole(request, ["admin", "coordinator"]);
  const versions = await getAllTimetableVersions();
  return { user, versions };
}

export async function action({ request }: ActionFunctionArgs) {
  const user = await requireRole(request, ["admin", "coordinator"]);
  const formData = await request.formData();
  const intent = formData.get("intent")?.toString();
  const versionId = Number(formData.get("versionId"));

  if (intent === "publish") {
    try {
      await publishTimetableVersion(versionId, user.id);
      return { success: true };
    } catch (err: any) {
      return { success: false, error: err.message };
    }
  }

  if (intent === "delete") {
    try {
      await deleteTimetableVersion(versionId, user.id);
      return { success: true };
    } catch (err: any) {
      return { success: false, error: err.message };
    }
  }

  return { success: false, error: "Invalid action" };
}

export default function TimetableVersionsPage() {
  const { versions } = useLoaderData<typeof loader>();
  const submit = useSubmit();

  const handlePublish = (versionId: number) => {
    if (!confirm("Are you sure you want to publish this timetable version?")) return;
    const formData = new FormData();
    formData.append("intent", "publish");
    formData.append("versionId", versionId.toString());
    submit(formData, { method: "post" });
  };

  const handleDelete = (versionId: number) => {
    if (!confirm("Are you sure you want to permanently delete this version and its entries?")) return;
    const formData = new FormData();
    formData.append("intent", "delete");
    formData.append("versionId", versionId.toString());
    submit(formData, { method: "post" });
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div>
          <h2 className="text-2xl font-bold tracking-tight text-slate-900 dark:text-white flex items-center gap-2">
            <History className="h-6 w-6 text-blue-600" />
            Timetable Version Management
          </h2>
          <p className="text-xs text-slate-500 mt-1">
            Track iteration history, compare optimization scores, and publish approved schedules.
          </p>
        </div>

        <Button asChild className="gap-2 shadow-md shadow-blue-500/20">
          <Link to="/timetable/generate">
            <Sparkles className="h-4 w-4" />
            Generate New Draft
          </Link>
        </Button>
      </div>

      <Card>
        <CardHeader>
          <CardTitle className="text-base">All Schedule Versions</CardTitle>
          <CardDescription>
            Only one version can be actively published per semester. Publishing a new version automatically archives the previous one.
          </CardDescription>
        </CardHeader>
        <CardContent>
          {versions.length === 0 ? (
            <div className="text-center py-12 space-y-3">
              <Calendar className="h-10 w-10 text-slate-300 dark:text-slate-700 mx-auto" />
              <p className="text-sm text-slate-500">No versions generated yet.</p>
              <Button asChild size="sm">
                <Link to="/timetable/generate">Generate Timetable</Link>
              </Button>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full text-left text-sm">
                <thead>
                  <tr className="border-b border-slate-200 dark:border-slate-800 text-xs font-semibold text-slate-400 uppercase">
                    <th className="pb-3">Version Name</th>
                    <th className="pb-3">Semester / Year</th>
                    <th className="pb-3">Status</th>
                    <th className="pb-3">Optimization Score</th>
                    <th className="pb-3">Generated By</th>
                    <th className="pb-3">Created</th>
                    <th className="pb-3 text-right">Actions</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                  {versions.map((ver) => (
                    <tr key={ver.id} className="hover:bg-slate-50/50 dark:hover:bg-slate-800/40">
                      <td className="py-3 font-semibold text-slate-900 dark:text-white">
                        {ver.name}
                      </td>
                      <td className="py-3 text-slate-600 dark:text-slate-300">
                        {ver.semester?.name} ({ver.academicYear?.name})
                      </td>
                      <td className="py-3">
                        <Badge
                          variant={
                            ver.status === "published"
                              ? "success"
                              : ver.status === "draft"
                              ? "secondary"
                              : "outline"
                          }
                          className="capitalize text-xs font-semibold"
                        >
                          {ver.status}
                        </Badge>
                      </td>
                      <td className="py-3 font-semibold text-slate-800 dark:text-slate-200">
                        {ver.optimizationScore} / 100
                      </td>
                      <td className="py-3 text-slate-500 text-xs">
                        {ver.generatedByUser?.fullName || "System Engine"}
                      </td>
                      <td className="py-3 text-slate-400 text-xs">
                        {new Date(ver.createdAt).toLocaleDateString()}
                      </td>
                      <td className="py-3 text-right">
                        <div className="flex items-center justify-end gap-2">
                          <Button asChild variant="outline" size="sm" className="h-8 gap-1 text-xs">
                            <Link to={`/timetable?versionId=${ver.id}`}>
                              <Eye className="h-3.5 w-3.5" />
                              View
                            </Link>
                          </Button>

                          {ver.status !== "published" && (
                            <Button
                              type="button"
                              variant="outline"
                              size="sm"
                              onClick={() => handlePublish(ver.id)}
                              className="h-8 gap-1 text-xs text-emerald-600 hover:text-emerald-700 hover:bg-emerald-50 dark:hover:bg-emerald-950/40"
                            >
                              <FileCheck className="h-3.5 w-3.5" />
                              Publish
                            </Button>
                          )}

                          <Button
                            type="button"
                            variant="ghost"
                            size="icon"
                            onClick={() => handleDelete(ver.id)}
                            title="Delete Version"
                            className="h-8 w-8 text-slate-400 hover:text-rose-600"
                          >
                            <Trash2 className="h-4 w-4" />
                          </Button>
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </CardContent>
      </Card>
    </div>
  );
}
